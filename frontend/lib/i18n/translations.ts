/** Replace `{key}` placeholders in a translation string. */
export function fill(template: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce<string>(
    (s, [k, v]) => s.replaceAll(`{${k}}`, String(v)),
    template
  );
}

// Widen all leaf literals to string so any locale can satisfy this type
export type Translations = {
  readonly [K in keyof typeof translations.en]: {
    readonly [P in keyof typeof translations.en[K]]: string;
  };
};
