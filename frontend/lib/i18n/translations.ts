/** Replace `{key}` placeholders in a translation string. */
export function fill(template: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce<string>(
    (s, [k, v]) => s.replaceAll(`{${k}}`, String(v)),
    template
  );
}

